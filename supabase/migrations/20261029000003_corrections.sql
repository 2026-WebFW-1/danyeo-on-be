-- 사용자가 자동 결과를 고친 기록. 종류마다 가리키는 사진 수가 달라 correction_photos 로 푼다
create table public.corrections (
    id         varchar(40) primary key,
    owner_id   uuid        not null default auth.uid() references public.profiles (id) on delete cascade,
    type       varchar(10) not null check (type in ('rename', 'exclude', 'transit', 'mode', 'split', 'merge')),
    name       varchar(100),
    mode       varchar(10) check (mode in ('flight', 'train', 'car')),
    created_at timestamptz not null default now(),
    constraint ck_corrections_name check ((type = 'rename') = (name is not null)),
    constraint ck_corrections_mode check ((type = 'mode') = (mode is not null))
);

create index idx_corrections_owner_id on public.corrections (owner_id);

create table public.correction_photos (
    id            bigint      generated by default as identity primary key,
    correction_id varchar(40) not null references public.corrections (id) on delete cascade,
    photo_id      varchar(40) not null references public.photos (id) on delete cascade,
    seq           integer     not null,
    constraint uk_correction_photos_photo unique (correction_id, photo_id),
    constraint uk_correction_photos_seq unique (correction_id, seq)
);

create index idx_correction_photos_photo_id on public.correction_photos (photo_id);

alter table public.corrections enable row level security;
alter table public.correction_photos enable row level security;

create policy "본인 보정" on public.corrections
    for all to authenticated
    using ((select auth.uid()) = owner_id)
    with check ((select auth.uid()) = owner_id);

-- 보정도 사진도 본인 것일 때만 잇는다
create policy "본인 보정의 사진" on public.correction_photos
    for all to authenticated
    using (exists (select 1 from public.corrections c where c.id = correction_id and c.owner_id = (select auth.uid())))
    with check (
        exists (select 1 from public.corrections c where c.id = correction_id and c.owner_id = (select auth.uid()))
        and exists (select 1 from public.photos p where p.id = photo_id and p.owner_id = (select auth.uid()))
    );

revoke all on public.corrections, public.correction_photos from anon, authenticated;
grant select, insert, update, delete on public.corrections, public.correction_photos to authenticated;
