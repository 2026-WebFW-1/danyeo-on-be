-- 사진 EXIF 의 제조사·모델 한 쌍. 모든 사용자가 같이 쓴다
create table public.cameras (
    id    bigint       generated by default as identity primary key,
    make  varchar(100) not null,
    model varchar(100) not null,
    constraint uk_cameras_make_model unique (make, model)
);

alter table public.cameras enable row level security;

create policy "카메라 읽기" on public.cameras for select to authenticated using (true);
create policy "카메라 추가" on public.cameras for insert to authenticated with check (true);

revoke all on public.cameras from anon, authenticated;
grant select, insert on public.cameras to authenticated;

-- 사진 메타데이터. ID 는 브라우저가 만든 값(p_xxxxxx)을 그대로 받는다
create table public.photos (
    id          varchar(40)      primary key,
    owner_id    uuid             not null default auth.uid() references public.profiles (id) on delete cascade,
    camera_id   bigint           references public.cameras (id),
    file_name   varchar(255)     not null,
    -- 현지 시각. 시간대는 utc_offset 에 따로 둔다
    taken_at    timestamp,
    utc_offset  varchar(6)       check (utc_offset ~ '^[+-][0-9]{2}:[0-9]{2}$'),
    lat         double precision check (lat between -90 and 90),
    lng         double precision check (lng between -180 and 180),
    focal       double precision,
    aperture    double precision,
    shutter     double precision,
    iso         integer,
    file_key    varchar(1000),
    uploaded_at timestamptz      not null default now(),
    -- 같은 사진을 다시 올리면 건너뛴다. 촬영 시각이 없는 사진끼리도 같은 것으로 본다
    constraint uk_photos_owner_file unique nulls not distinct (owner_id, file_name, taken_at),
    constraint ck_photos_lat_lng check ((lat is null) = (lng is null))
);

create index idx_photos_camera_id on public.photos (camera_id);

alter table public.photos enable row level security;

create policy "본인 사진" on public.photos
    for all to authenticated
    using ((select auth.uid()) = owner_id)
    with check ((select auth.uid()) = owner_id);

revoke all on public.photos from anon, authenticated;
grant select, insert, update, delete on public.photos to authenticated;
