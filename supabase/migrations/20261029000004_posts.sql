-- 날짜에 붙는 글. 현지 날짜 기준이고 하루에 여러 개 쓸 수 있다
create table public.posts (
    id         varchar(40)  primary key,
    owner_id   uuid         not null default auth.uid() references public.profiles (id) on delete cascade,
    post_date  date         not null,
    title      varchar(200) not null,
    body       text         not null default '' check (char_length(body) <= 10000),
    updated_at timestamptz  not null default now()
);

create index idx_posts_owner_date on public.posts (owner_id, post_date);

create table public.post_photos (
    id       bigint      generated by default as identity primary key,
    post_id  varchar(40) not null references public.posts (id) on delete cascade,
    photo_id varchar(40) not null references public.photos (id) on delete cascade,
    seq      integer     not null,
    constraint uk_post_photos_photo unique (post_id, photo_id),
    constraint uk_post_photos_seq unique (post_id, seq)
);

create index idx_post_photos_photo_id on public.post_photos (photo_id);

create table public.post_tags (
    post_id varchar(40) not null references public.posts (id) on delete cascade,
    tag     varchar(50) not null,
    primary key (post_id, tag)
);

alter table public.posts enable row level security;
alter table public.post_photos enable row level security;
alter table public.post_tags enable row level security;

create policy "본인 글" on public.posts
    for all to authenticated
    using ((select auth.uid()) = owner_id)
    with check ((select auth.uid()) = owner_id);

create policy "본인 글의 사진" on public.post_photos
    for all to authenticated
    using (exists (select 1 from public.posts p where p.id = post_id and p.owner_id = (select auth.uid())))
    with check (
        exists (select 1 from public.posts p where p.id = post_id and p.owner_id = (select auth.uid()))
        and exists (select 1 from public.photos ph where ph.id = photo_id and ph.owner_id = (select auth.uid()))
    );

create policy "본인 글의 태그" on public.post_tags
    for all to authenticated
    using (exists (select 1 from public.posts p where p.id = post_id and p.owner_id = (select auth.uid())))
    with check (exists (select 1 from public.posts p where p.id = post_id and p.owner_id = (select auth.uid())));

revoke all on public.posts, public.post_photos, public.post_tags from anon, authenticated;
grant select, insert, update, delete on public.posts, public.post_photos, public.post_tags to authenticated;
